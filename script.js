function displayVideo(videos) {
  const videoList = document.querySelector("#video-list");

  videoList.innerHTML = "";

  videos.forEach((video) => {
    const videoItem = document.createElement("div");
    videoItem.className = "video-item";
    videoItem.innerHTML = `
           
    <div class="video-thumbnail" style="background-image: url(${video.thumbnail[0].url});width:300px; height:202px;"></div>

        <div class="video-info">
           <div class="video-title">${video.title}</div>
           <div class="video-channel">${video.channelTitle}</div>
        </div>

        `;

      videoItem.addEventListener("click", ()=> openModel(video.videoId))

      videoList.appendChild(videoItem);
  });
}

function openModel(videoId) {
  const model = document.querySelector("#video-model")
  const videoPlayer = document.querySelector("#video-player")
  const videoURL = `https://www.youtube.com/embed/${videoId}`

  videoPlayer.src = videoURL;
  model.style.display = "block"

  // download the video

  document.querySelector("#download-as-mp3").addEventListener("click", async ()=> {
   
    const url = `https://youtube-mp36.p.rapidapi.com/dl?id=${videoId}`;

    const options = {
      method: "GET",
      headers: {
        "x-rapidapi-key" : "b6ca8b2f10msh97193ff4380bbe1p1b0466jsnce072874424a",
        "x-rapidapi-host" : "youtube-mp36.p.rapidapi.com",
      }
    }

    try {
      const response = await fetch(url,options)
      const result = await response.json()

      if(result.status === "ok") {
        window.location.href = result.link;
      } else {
        alert("Error downloading MP3")
      }

    } catch (error) {
      console.error("error", error)
    }
        
  })

}

document.querySelector(".close-model").addEventListener("click", closeModel)

function closeModel() {
  const model = document.querySelector("#video-model")
  const videoPlayer = document.querySelector("#video-player")

  videoPlayer.src = "";
  model.style.display = "none"
}

window.onclick = function(event) {
  const model = document.querySelector("#video-model")

  if(event.target == model) {
    closeModel()
  }
}



